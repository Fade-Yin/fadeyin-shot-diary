const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../ui/interaction-update.js'),'utf8');
const code=source.slice(source.indexOf('let densityFrame=0;'),source.indexOf('const densityObserver='));
let width=1000,callback;
const elements=[.1,.7,.8,3.5,3.6,7.1,7.2].map(n=>({style:{width:n+'%'},classes:new Set(),classList:{toggle(name,on){on?this.owner.classes.add(name):this.owner.classes.delete(name)}}}));
elements.forEach(e=>e.classList.owner=e);
const surface={getBoundingClientRect:()=>({width}),querySelectorAll:()=>elements};
const context=vm.createContext({$:()=>surface,document:{querySelector:()=>null},requestAnimationFrame:fn=>{callback=fn;return 1}});
vm.runInContext(code+';scheduleDensity()',context);callback();
assert(elements[0].classes.has('densityTiny'));
assert(elements[1].classes.has('densityTiny'));
assert(!elements[2].classes.has('densityTiny'));
assert(elements[3].classes.has('densityCompact'));
assert(!elements[4].classes.has('densityCompact'));
assert(elements[5].classes.has('densityNoImage'));
assert(!elements[6].classes.has('densityNoImage'));
width=100000;vm.runInContext('scheduleDensity()',context);callback();
assert.equal(elements[0].classes.size,0,'Zooming restores details');
width=0;vm.runInContext('scheduleDensity()',context);callback();
width=1000;vm.runInContext('scheduleDensity()',context);callback();
assert(!elements[6].classes.has('densityNoImage'),'Reopening restores measured detail');
console.log('PASS density boundaries, zoom restoration, hidden-panel restoration (DOM-double, not visual acceptance)');
